// Smoke test + mobile screenshots using headless Chrome with a fake microphone.
import { chromium } from 'playwright-core'
import { mkdirSync, statSync } from 'node:fs'

const BASE = process.env.BASE ?? 'http://localhost:4173'
const OUT = process.env.OUT ?? '/workspace/courtscribe/shots'
mkdirSync(OUT, { recursive: true })
mkdirSync('/tmp/cs-dl', { recursive: true })
const browser = await chromium.launch({
  executablePath: '/usr/bin/google-chrome',
  args: ['--no-sandbox', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--autoplay-policy=no-user-gesture-required'],
})
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, permissions: ['microphone'], acceptDownloads: true })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
page.on('console', (m) => m.type() === 'error' && errors.push('console: ' + m.text()))
const step = (s) => console.log('▶', s)

step('home (empty)')
await page.goto(BASE + '/')
await page.getByText('No sessions yet').waitFor()

step('new session')
await page.getByRole('link', { name: 'Record' }).last().click()
await page.getByLabel('Title').fill('People v. Santos — Hearing 01')
await page.getByLabel('Case / reference no. (optional)').fill('Crim. Case No. R-QZN-24-01234')
await page.getByLabel('Court or venue (optional)').fill('RTC Branch 12, Quezon City')
await page.getByLabel('Name for participant 1').fill('Hon. M. Reyes')
await page.getByLabel('Name for participant 3').fill('Atty. Cruz')
await page.getByLabel('Name for participant 4').fill('J. Dela Cruz')
await page.getByRole('radio', { name: /Hybrid/ }).click()
await page.getByLabel('Speech recognition').selectOption('mock')
await page.getByRole('button', { name: 'Test mic' }).click()
await page.getByText('Working — speak to see the input level.').waitFor()
// validation: try start without authorization
await page.getByRole('button', { name: 'Start recording' }).click()
await page.getByText('You must confirm authorization before recording').waitFor()
await page.locator('input[type=checkbox]').first().check()
await page.screenshot({ path: `${OUT}/02-new-session.png`, fullPage: false })
await page.getByRole('button', { name: 'Start recording' }).click()
await page.waitForURL(/\/live\//)
step('live recording (demo provider)')
await page.waitForTimeout(9000)
await page.getByRole('button', { name: 'Bookmark' }).click()
await page.getByRole('button', { name: 'Objection' }).click()
await page.getByRole('button', { name: 'Add bookmark' }).click()
await page.waitForTimeout(9000)
// manual steno line
await page.getByLabel('Manual transcript entry').pressSequentially('nfq ')
const v = await page.getByLabel('Manual transcript entry').inputValue()
if (!v.startsWith('No further questions, Your Honor.')) throw new Error('steno expansion failed in live composer: ' + v)
await page.getByLabel('Manual transcript entry').press('Enter')
await page.waitForTimeout(2500)
await page.screenshot({ path: `${OUT}/03-live-transcription.png` })
const segCount = await page.locator('[data-segment-id]').count()
step(`segments visible: ${segCount}`)
// scroll up to trigger Jump to Live
await page.evaluate(() => { const el = document.querySelector('[aria-live="polite"]'); if (el) el.scrollTop = 0 })
await page.waitForTimeout(600)
const jump = await page.getByRole('button', { name: 'Jump to Live' }).count()
step(`jump to live shown: ${jump > 0}`)
// pause & resume
await page.getByRole('button', { name: 'Pause recording' }).click()
await page.getByText('PAUSED', { exact: false }).first().waitFor()
await page.getByRole('button', { name: 'Resume recording' }).click()
await page.waitForTimeout(6000)
step('stop')
await page.getByRole('button', { name: 'Stop', exact: true }).click()
await page.getByRole('button', { name: 'Stop and save' }).click()
await page.waitForURL(/\/sessions\/[^/]+$/)
await page.locator('[data-segment-id]').first().waitFor()
step('review: edit first segment')
await page.getByRole('button', { name: 'Edit segment' }).nth(1).click()
const ta = page.getByLabel('Segment text')
await ta.fill('Yes, Your Honor. We are ready to proceed with the witness.')
await page.getByRole('button', { name: 'Save', exact: true }).click()
await page.locator('article span', { hasText: 'Corrected' }).first().waitFor()
await page.getByRole('button', { name: 'Mark reviewed' }).first().click()
await page.waitForTimeout(500)
await page.evaluate(() => window.scrollTo(0, 0))
await page.waitForTimeout(300)
await page.screenshot({ path: `${OUT}/04-session-review.png` })
// undo
await page.getByRole('button', { name: /^Undo/ }).click()
await page.waitForTimeout(300)
step('export')
await page.getByRole('link', { name: /Export/ }).click()
await page.getByText('Preview (text layout)').waitFor()
for (const [label, fmt] of [['Word (.docx)', 'docx'], ['PDF', 'pdf'], ['Plain text', 'txt'], ['Subtitles', 'srt'], ['Structured JSON', 'json']]) {
  await page.getByRole('button', { name: new RegExp('^' + label.replace(/[()\.]/g, '\\$&')) }).first().click()
  const [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: /^Download/ }).click()])
  const p = `/tmp/cs-dl/${dl.suggestedFilename()}`
  await dl.saveAs(p)
  console.log(`   ${fmt}: ${dl.suggestedFilename()} ${statSync(p).size} bytes`)
}
const [adl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: /Original audio/ }).click()])
await adl.saveAs(`/tmp/cs-dl/${adl.suggestedFilename()}`)
console.log(`   audio: ${adl.suggestedFilename()} ${statSync(`/tmp/cs-dl/${adl.suggestedFilename()}`).size} bytes`)

step('crash recovery: start session then reload without stopping')
await page.goto(BASE + '/record')
await page.getByLabel('Title').fill('Interview — Barangay Hall')
await page.getByLabel('Speech recognition').selectOption('mock')
await page.locator('input[type=checkbox]').first().check()
await page.getByRole('button', { name: 'Start recording' }).click()
await page.waitForURL(/\/live\//)
await page.waitForTimeout(7000)
await page.evaluate(() => window.onbeforeunload = null)
// simulate crash: navigate away hard (beforeunload listener bypassed by goto)
const p2 = await ctx.newPage()
await page.close({ runBeforeUnload: false })
await p2.waitForTimeout(13000)
await p2.goto(BASE + '/')
await p2.getByText('Interrupted session recovered').waitFor({ timeout: 10000 })
await p2.waitForTimeout(800)
await p2.screenshot({ path: `${OUT}/01-home-recovery.png` })
step('steno page')
await p2.goto(BASE + '/steno')
await p2.getByLabel('Shorthand practice pad').pressSequentially('yh, the sw is here. obj ')
console.log('   pad:', await p2.getByLabel('Shorthand practice pad').inputValue())
await p2.screenshot({ path: `${OUT}/05-steno.png` })
await p2.goto(BASE + '/settings')
await p2.screenshot({ path: `${OUT}/06-settings.png` })
// desktop layout
const d = p2
await d.setViewportSize({ width: 1280, height: 800 })
await d.goto(BASE + '/sessions')
await d.waitForTimeout(800)
await d.screenshot({ path: `${OUT}/07-desktop-sessions.png` })
console.log('errors:', errors.length ? errors : 'none')
await browser.close()
